/**
 * Export to WordPress:
 *   <slug>-theme.zip  – a block theme (theme.json, templates/, parts/, style.css)
 *   content.xml       – WXR file with every page's post_content
 *   site.json         – the builder's own project file (re-importable)
 *   static/           – rendered HTML of each page (works without WordPress)
 */
import JSZip from 'jszip';
import type { Site } from '../types';
import { TARGET_WP_VERSION } from '../types';
import { buildThemeJson, googleFontsUrl } from './design';
import { renderPage } from './render';
import { HOME_SLUG, templates } from './templates';
import { validateMarkup } from './markup';
import { blockSlug, registerCustomBlocks } from './customBlocks';
import { blockJson, blockStyleCss, comment, editorScript, functionsPhpBlocks, HELPERS_PHP, patternPhp, renderPhp } from './wpBlocks';

export function themeSlug(site: Site) {
  return (
    site.name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '')
      .slice(0, 40) || 'site'
  );
}

const cdata = (s: string) => `<![CDATA[${String(s).split(']]>').join(']]]]><![CDATA[>')}]]>`;
const xmlEsc = (s: string) => String(s).replace(/[<>&"]/g, (c) => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;', '"': '&quot;' })[c]!);
const phpStr = (s: string) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

export function buildWxr(site: Site, baseUrl = 'https://example.com'): string {
  const now = new Date();
  const date = now.toISOString().slice(0, 19).replace('T', ' ');
  const items = site.pages
    .map(
      (p, i) => `
  <item>
    <title>${cdata(p.title)}</title>
    <link>${xmlEsc(baseUrl + (p.slug === HOME_SLUG ? '/' : `/${p.slug}/`))}</link>
    <pubDate>${now.toUTCString()}</pubDate>
    <dc:creator>${cdata('admin')}</dc:creator>
    <guid isPermaLink="false">${xmlEsc(`${baseUrl}/?page_id=${1000 + i}`)}</guid>
    <description></description>
    <content:encoded>${cdata(p.content)}</content:encoded>
    <excerpt:encoded>${cdata('')}</excerpt:encoded>
    <wp:post_id>${1000 + i}</wp:post_id>
    <wp:post_date>${cdata(date)}</wp:post_date>
    <wp:post_date_gmt>${cdata(date)}</wp:post_date_gmt>
    <wp:post_modified>${cdata(date)}</wp:post_modified>
    <wp:post_modified_gmt>${cdata(date)}</wp:post_modified_gmt>
    <wp:comment_status>${cdata('closed')}</wp:comment_status>
    <wp:ping_status>${cdata('closed')}</wp:ping_status>
    <wp:post_name>${cdata(p.slug)}</wp:post_name>
    <wp:status>${cdata('publish')}</wp:status>
    <wp:post_parent>0</wp:post_parent>
    <wp:menu_order>${i}</wp:menu_order>
    <wp:post_type>${cdata('page')}</wp:post_type>
    <wp:post_password>${cdata('')}</wp:post_password>
    <wp:is_sticky>0</wp:is_sticky>
  </item>`,
    )
    .join('');
  // Synced patterns: wp_block posts. Their post ids are the refs used in content
  // (<!-- wp:block {"ref":N} /-->); the importer keeps the id on a fresh install.
  const patternItems = (site.patterns ?? [])
    .filter((p) => p.synced)
    .map(
      (p) => `
  <item>
    <title>${cdata(p.title)}</title>
    <pubDate>${now.toUTCString()}</pubDate>
    <dc:creator>${cdata('admin')}</dc:creator>
    <guid isPermaLink="false">${xmlEsc(`${baseUrl}/?p=${p.id}`)}</guid>
    <content:encoded>${cdata(p.content)}</content:encoded>
    <wp:post_id>${p.id}</wp:post_id>
    <wp:post_date>${cdata(date)}</wp:post_date>
    <wp:post_date_gmt>${cdata(date)}</wp:post_date_gmt>
    <wp:comment_status>${cdata('closed')}</wp:comment_status>
    <wp:ping_status>${cdata('closed')}</wp:ping_status>
    <wp:post_name>${cdata(p.slug)}</wp:post_name>
    <wp:status>${cdata('publish')}</wp:status>
    <wp:post_parent>0</wp:post_parent>
    <wp:menu_order>0</wp:menu_order>
    <wp:post_type>${cdata('wp_block')}</wp:post_type>
    <wp:post_password>${cdata('')}</wp:post_password>
    <wp:is_sticky>0</wp:is_sticky>
  </item>`,
    )
    .join('');
  return `<?xml version="1.0" encoding="UTF-8" ?>
<!-- WordPress eXtended RSS export generated by Prepress. Import via Tools → Import → WordPress. -->
<rss version="2.0"
  xmlns:excerpt="http://wordpress.org/export/1.2/excerpt/"
  xmlns:content="http://purl.org/rss/1.0/modules/content/"
  xmlns:wfw="http://wellformedweb.org/CommentAPI/"
  xmlns:dc="http://purl.org/dc/elements/1.1/"
  xmlns:wp="http://wordpress.org/export/1.2/">
<channel>
  <title>${xmlEsc(site.name)}</title>
  <link>${xmlEsc(baseUrl)}</link>
  <description>${xmlEsc(site.tagline)}</description>
  <language>en-US</language>
  <wp:wxr_version>1.2</wp:wxr_version>
  <wp:base_site_url>${xmlEsc(baseUrl)}</wp:base_site_url>
  <wp:base_blog_url>${xmlEsc(baseUrl)}</wp:base_blog_url>
  <wp:author><wp:author_id>1</wp:author_id><wp:author_login>${cdata('admin')}</wp:author_login><wp:author_email>${cdata('')}</wp:author_email><wp:author_display_name>${cdata('admin')}</wp:author_display_name><wp:author_first_name>${cdata('')}</wp:author_first_name><wp:author_last_name>${cdata('')}</wp:author_last_name></wp:author>
  <generator>Prepress</generator>${patternItems}${items}
</channel>
</rss>
`;
}

function styleCss(site: Site, slug: string) {
  return `/*
Theme Name: ${comment(site.name)}
Description: ${comment(site.tagline || site.name)} — block theme generated by Prepress.
Version: 1.0.0
Requires at least: ${TARGET_WP_VERSION}
Tested up to: ${TARGET_WP_VERSION}
Requires PHP: 7.4
License: GNU General Public License v2 or later
License URI: http://www.gnu.org/licenses/gpl-2.0.html
Text Domain: ${slug}
*/
`;
}

function functionsPhp(site: Site, slug: string) {
  const fonts = googleFontsUrl(site.design);
  const fn = slug.replace(/-/g, '_');
  return `<?php
/**
 * ${comment(site.name)} — generated by Prepress.
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}
${
  fonts
    ? `
/**
 * Web fonts. TODO: self-host via theme.json fontFace (GDPR) — see README.
 */
function ${fn}_fonts() {
	wp_enqueue_style( '${slug}-fonts', ${phpStr(fonts)}, array(), null );
}
add_action( 'wp_enqueue_scripts', '${fn}_fonts' );

function ${fn}_editor_fonts() {
	add_editor_style( ${phpStr(fonts)} );
}
add_action( 'after_setup_theme', '${fn}_editor_fonts' );
`
    : ''
}
/**
 * One-time setup after content import: use the "home" page as the front page
 * and adopt the site title/tagline if WordPress still has its defaults.
 */
function ${fn}_one_time_setup() {
	if ( get_option( '${fn}_setup_done' ) ) {
		return;
	}
	$home = get_page_by_path( '${HOME_SLUG}' );
	if ( ! $home ) {
		return; // Content not imported yet — try again on a later request.
	}
	update_option( 'show_on_front', 'page' );
	update_option( 'page_on_front', $home->ID );
	if ( in_array( get_option( 'blogname' ), array( '', 'WordPress', 'My WordPress Website' ), true ) ) {
		update_option( 'blogname', ${phpStr(site.name)} );
	}
	if ( in_array( get_option( 'blogdescription' ), array( '', 'Just another WordPress site' ), true ) ) {
		update_option( 'blogdescription', ${phpStr(site.tagline)} );
	}
	update_option( '${fn}_setup_done', 1 );
}
add_action( 'admin_init', '${fn}_one_time_setup' );
${functionsPhpBlocks(site.blocks ?? [], (site.patterns ?? []).some((p) => !p.synced), fn, slug)}`;
}

function readme(site: Site, slug: string) {
  return `# ${site.name} — WordPress export

Generated by Prepress for WordPress ${TARGET_WP_VERSION}.

## What's inside

| File | What it is |
| --- | --- |
| \`${slug}-theme.zip\` | Block theme: \`theme.json\` (colors, fonts, spacing), \`templates/\`, \`parts/header.html\`, \`parts/footer.html\` |
| \`content.xml\` | WordPress export (WXR) with ${site.pages.length} pages. Every page is native Gutenberg block markup |
| \`site.json\` | Prepress project file. Re-import it in the builder to keep editing |
| \`static/\` | Plain HTML render of every page (handy for a quick look or static hosting) |

## Move it into WordPress

1. **Appearance → Themes → Add New → Upload Theme**, upload \`${slug}-theme.zip\`. Don't activate yet.
2. **Tools → Import → WordPress** (install the importer if asked), upload \`content.xml\`.
3. Activate the theme. On your next admin page load it sets the "${site.pages.find((p) => p.slug === HOME_SLUG)?.title ?? 'Home'}" page as the front page
   (and adopts the site title/tagline if WordPress still has its defaults).
4. Open any page in the block editor. Every block is a core block, so it should load with no
   "unexpected or invalid content" warnings. Global colors and fonts are in **Appearance → Editor → Styles**.

## Known gaps in this prototype

- Images are SVG placeholders stored as data URIs. Replace them in the editor (or use the media pipeline on the roadmap).
- Fonts load from Google Fonts. For GDPR, switch to self-hosted \`fontFace\` entries in theme.json.
- The header navigation is stored inline in the header template part (not as a \`wp_navigation\` post).
${
  (site.blocks ?? []).length
    ? `
## Site blocks

This theme registers ${site.blocks!.length} block type(s) made in Prepress (\`blocks/\`): ${site.blocks!.map((b) => `\`${b.name}\``).join(', ')}.
They are dynamic blocks rendered by \`render.php\` and edited with \`assets/prepress-blocks.js\` (no build step).
They live in the theme: if you switch themes, WordPress shows "This block is not available" for them until you move
\`blocks/\`, \`inc/prepress-blocks.php\` and \`assets/prepress-blocks.js\` into a plugin or the new theme.
`
    : ''
}${
  (site.patterns ?? []).length
    ? `
## Patterns

${(site.patterns ?? []).filter((p) => !p.synced).length} pattern(s) ship in \`patterns/\` (Inserter → Patterns → Site patterns).
${(site.patterns ?? []).filter((p) => p.synced).length} synced pattern(s) are in \`content.xml\` as reusable blocks; pages reference them by id,
which the importer keeps on a fresh install. Import into a site that already has posts with those ids (5000+) may break the references.
`
    : ''
}`;
}

export interface ExportResult {
  /** The zip, for browsers. */
  blob: Blob;
  /** The same zip as bytes, for the server. */
  bytes: Uint8Array;
  filename: string;
  stats: { pages: number; blocks: number; invalid: number };
}

export async function exportSite(site: Site): Promise<ExportResult> {
  const slug = themeSlug(site);
  const t = templates();
  const siteBlocks = site.blocks ?? [];
  registerCustomBlocks(siteBlocks);

  // Theme zip (WordPress expects a single top-level theme folder).
  const theme = new JSZip();
  const tf = theme.folder(slug)!;
  tf.file('style.css', styleCss(site, slug));
  tf.file('theme.json', JSON.stringify(buildThemeJson(site.design, site.themeJson), null, '\t'));
  tf.file('functions.php', functionsPhp(site, slug));
  tf.file('templates/index.html', t.index);
  tf.file('templates/single.html', t.single);
  tf.file('templates/page.html', t.page);
  tf.file('templates/front-page.html', t.page);
  tf.file('parts/header.html', site.header);
  tf.file('parts/footer.html', site.footer);
  // Site blocks: block.json + render.php (+ style.css) each, shared helpers and the editor script.
  for (const def of siteBlocks) {
    const dir = `blocks/${blockSlug(def.name)}`;
    tf.file(`${dir}/block.json`, JSON.stringify(blockJson(def, slug), null, '\t'));
    tf.file(`${dir}/render.php`, renderPhp(def));
    if (def.css) tf.file(`${dir}/style.css`, blockStyleCss(def));
  }
  if (siteBlocks.length) {
    tf.file('inc/prepress-blocks.php', HELPERS_PHP);
    tf.file('assets/prepress-blocks.js', editorScript(siteBlocks));
  }
  for (const p of (site.patterns ?? []).filter((x) => !x.synced)) tf.file(`patterns/${p.slug}.php`, patternPhp(p, slug));
  tf.file('readme.txt', `=== ${site.name} ===\nRequires at least: ${TARGET_WP_VERSION}\nTested up to: ${TARGET_WP_VERSION}\nLicense: GPLv2 or later\n\nBlock theme generated by Prepress.\n`);
  const themeBlob = await theme.generateAsync({ type: 'uint8array', compression: 'DEFLATE' });

  let blocks = 0;
  let invalid = 0;
  for (const markup of [...site.pages.map((p) => p.content), site.header, site.footer, ...(site.patterns ?? []).map((p) => p.content), t.page, t.index, t.single]) {
    const v = validateMarkup(markup);
    blocks += v.blocks;
    invalid += v.invalid.length;
  }

  const bundle = new JSZip();
  const root = bundle.folder(`${slug}-wordpress`)!;
  root.file('README.md', readme(site, slug));
  root.file(`${slug}-theme.zip`, themeBlob);
  root.file('content.xml', buildWxr(site));
  root.file('site.json', JSON.stringify({ format: 'prepress/site@1', wordpress: TARGET_WP_VERSION, site }, null, 2));
  for (const p of site.pages) {
    root.file(`static/${p.slug === HOME_SLUG ? 'index' : p.slug}.html`, staticPage(site, p.id));
  }
  const bytes = await bundle.generateAsync({ type: 'uint8array', compression: 'DEFLATE' });
  const blob = new Blob([bytes as BlobPart], { type: 'application/zip' });
  return { blob, bytes, filename: `${slug}-wordpress.zip`, stats: { pages: site.pages.length, blocks, invalid } };
}

function staticPage(site: Site, pageId: string) {
  const page = site.pages.find((p) => p.id === pageId)!;
  // Rewrite pretty permalinks to relative .html files for the static copy.
  return renderPage(site, page).replace(/href="\/([\w-]*)\/?"/g, (_m, s) => `href="./${s ? s : 'index'}.html"`);
}
