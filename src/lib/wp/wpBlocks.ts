/**
 * Turns site-defined blocks into files a WordPress block theme can register:
 *
 *   blocks/<slug>/block.json   metadata (attributes, supports, render, style)
 *   blocks/<slug>/render.php   the template compiled to PHP (front end)
 *   blocks/<slug>/style.css    the block's CSS
 *   inc/prepress-blocks.php    escaping helpers shared by every render.php
 *   assets/prepress-blocks.js  editor UI (no build step; uses the wp.* globals)
 *
 * render.php and the editor script implement exactly the template rules of
 * fillTemplate() in customBlocks.ts — tests run all three side by side.
 */
import type { CustomBlockDef } from '../types';
import { blockJsonAttributes, blockSlug, CUSTOM_SUPPORTS, hasContentSlot, sanitizeCss } from './customBlocks';

/** Text safe inside a PHP/CSS block comment (an AI-supplied title must not end the comment). */
export const comment = (s: string) => String(s).replace(/\*\//g, '* /').replace(/[\r\n]+/g, ' ').replace(/\?>/g, '? >');

const php = (s: string) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

export function blockJson(def: CustomBlockDef, textDomain: string) {
  return {
    $schema: 'https://schemas.wp.org/trunk/block.json',
    apiVersion: 3,
    name: def.name,
    title: def.title,
    category: def.category,
    icon: def.icon || 'block-default',
    ...(def.description ? { description: def.description } : {}),
    textdomain: textDomain,
    attributes: blockJsonAttributes(def),
    supports: CUSTOM_SUPPORTS,
    editorScript: 'prepress-blocks-editor',
    ...(def.css ? { style: 'file:./style.css' } : {}),
    render: 'file:./render.php',
  };
}

/** Compile a template to PHP. Assumes balanced sections (cleanBlockDef enforces it). */
export function compileTemplateToPhp(def: Pick<CustomBlockDef, 'template' | 'attributes'>): string {
  const out: string[] = [];
  const re = /\{\{\{content\}\}\}|\{\{([#^/])?([a-zA-Z][a-zA-Z0-9]*)\}\}/g;
  let last = 0;
  const text = (t: string) => t.replace(/<\?/g, '&lt;?');
  for (const m of def.template.matchAll(re)) {
    out.push(text(def.template.slice(last, m.index)));
    last = m.index! + m[0].length;
    if (m[0] === '{{{content}}}') {
      out.push('<?php echo $content; // phpcs:ignore WordPress.Security.EscapeOutput -- rendered inner blocks ?>');
      continue;
    }
    const [, kind, key] = m;
    if (kind === '#') out.push(`<?php if ( prepress_truthy( $attributes[${php(key)}] ?? null ) ) : ?>`);
    else if (kind === '^') out.push(`<?php if ( ! prepress_truthy( $attributes[${php(key)}] ?? null ) ) : ?>`);
    else if (kind === '/') out.push('<?php endif; ?>');
    else {
      const a = def.attributes[key];
      out.push(`<?php echo prepress_fmt( $attributes, ${php(key)}, ${php(a?.control ?? 'text')}, ${php(a?.type ?? 'string')} ); // phpcs:ignore WordPress.Security.EscapeOutput -- escaped by prepress_fmt ?>`);
    }
  }
  out.push(text(def.template.slice(last)));
  return out.join('');
}

export function renderPhp(def: CustomBlockDef): string {
  return `<?php
/**
 * ${comment(def.title)} (${def.name}) — generated by Prepress.
 *
 * @var array    $attributes Block attributes (defaults applied).
 * @var string   $content    Rendered inner blocks.
 * @var WP_Block $block      Block instance.
 */
if ( ! defined( 'ABSPATH' ) ) {
	exit;
}
?>
<div <?php echo get_block_wrapper_attributes(); // phpcs:ignore WordPress.Security.EscapeOutput ?>>${compileTemplateToPhp(def)}</div>
`;
}

export const HELPERS_PHP = `<?php
/**
 * Template helpers for Prepress blocks (each blocks/<name>/render.php).
 * Keep in sync with fillTemplate() in Prepress (src/lib/wp/customBlocks.ts).
 */
if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

if ( ! function_exists( 'prepress_truthy' ) ) {
	function prepress_truthy( $v ) {
		return ! ( null === $v || false === $v || '' === $v || 0 === $v || 0.0 === $v );
	}
}

if ( ! function_exists( 'prepress_esc_url' ) ) {
	/** esc_url(), but keeps data:image URIs (Prepress placeholders). */
	function prepress_esc_url( $url ) {
		$url = trim( (string) $url );
		if ( '' === $url ) {
			return '';
		}
		if ( preg_match( '#^data:image/(png|jpe?g|gif|webp|avif|svg\\+xml)[;,]#i', $url ) ) {
			return esc_html( $url );
		}
		return esc_url( $url );
	}
}

if ( ! function_exists( 'prepress_fmt' ) ) {
	function prepress_fmt( $attributes, $key, $control, $type ) {
		if ( ! isset( $attributes[ $key ] ) ) {
			return '';
		}
		$v = $attributes[ $key ];
		if ( 'url' === $control || 'image' === $control ) {
			return prepress_esc_url( $v );
		}
		if ( 'richtext' === $control ) {
			return wp_kses_post( (string) $v );
		}
		if ( 'boolean' === $type ) {
			return $v ? 'true' : '';
		}
		if ( 'number' === $type ) {
			return is_numeric( $v ) ? (string) ( 0 + $v ) : '';
		}
		return esc_html( (string) $v );
	}
}
`;

export function blockStyleCss(def: CustomBlockDef): string {
  return `/* ${comment(def.title)} (${def.name}) — generated by Prepress. */\n${sanitizeCss(def.css)}\n`;
}

/**
 * Editor script for WordPress: registers each block's edit/save on top of the
 * server-registered block.json metadata. Plain ES2017, wp.* globals, no build.
 */
export function editorScript(defs: CustomBlockDef[]): string {
  const data = defs.map((d) => ({
    name: d.name,
    template: d.template,
    attributes: d.attributes,
    content: hasContentSlot(d),
    allowed: d.innerBlocks?.allowed ?? null,
    innerTemplate: d.innerBlocks?.template ? toTemplate(d.innerBlocks.template) : null,
  }));
  return `/* Prepress blocks — editor UI. Generated by Prepress; edit the blocks in Prepress and re-export. */
(function (wp, DEFS) {
  'use strict';
${RUNTIME}
  if (!wp || !wp.blocks) return;
  var el = wp.element.createElement;
  var be = wp.blockEditor;
  var c = wp.components;
  var SLOT = '<div data-pp-slot></div>';

  function Field(p) {
    var a = p.def, label = a.label || p.name, v = p.value;
    var common = { label: label, __nextHasNoMarginBottom: true, __next40pxDefaultSize: true };
    function set(x) { var o = {}; o[p.name] = x; p.setAttributes(o); }
    switch (a.control) {
      case 'toggle': return el(c.ToggleControl, Object.assign({}, common, { checked: !!v, onChange: set }));
      case 'textarea': case 'richtext': return el(c.TextareaControl, Object.assign({}, common, { value: v || '', onChange: set }));
      case 'number': return el(c.TextControl, Object.assign({}, common, { type: 'number', value: v === undefined ? '' : v, onChange: function (x) { set(x === '' ? undefined : Number(x)); } }));
      case 'select': return el(c.SelectControl, Object.assign({}, common, { value: v || '', options: (a.options || []).map(function (o) { return { label: o, value: o }; }), onChange: set }));
      case 'image':
        return el('div', { className: 'prepress-field-image' },
          el(c.TextControl, Object.assign({}, common, { type: 'url', value: v || '', onChange: set })),
          el(be.MediaUploadCheck, null, el(be.MediaUpload, { allowedTypes: ['image'], onSelect: function (m) { set(m && m.url); }, render: function (r) { return el(c.Button, { variant: 'secondary', onClick: r.open }, 'Choose image'); } })));
      case 'url': return el(c.TextControl, Object.assign({}, common, { type: 'url', value: v || '', onChange: set }));
      default: return el(c.TextControl, Object.assign({}, common, { value: v || '', onChange: set }));
    }
  }

  function Inner(p) {
    var props = be.useInnerBlocksProps({ className: 'prepress-inner' }, { allowedBlocks: p.allowed || undefined, template: p.template || undefined, templateLock: false });
    return el('div', props);
  }

  DEFS.forEach(function (def) {
    function Edit(props) {
      var attrs = props.attributes;
      var html = fill(def, attrs, def.content ? SLOT : '');
      var host = wp.element.useRef(null);
      var st = wp.element.useState(null), slot = st[0], setSlot = st[1];
      wp.element.useLayoutEffect(function () { setSlot(def.content && host.current ? host.current.querySelector('[data-pp-slot]') : null); }, [html]);
      return el(wp.element.Fragment, null,
        el(be.InspectorControls, null, el(c.PanelBody, { title: 'Settings' }, Object.keys(def.attributes).map(function (k) { return el(Field, { key: k, name: k, def: def.attributes[k], value: attrs[k], setAttributes: props.setAttributes }); }))),
        el('div', be.useBlockProps(),
          el('div', { ref: host, style: { display: 'contents' }, dangerouslySetInnerHTML: { __html: html } }),
          slot ? wp.element.createPortal(el(Inner, { allowed: def.allowed, template: def.innerTemplate }), slot) : null));
    }
    wp.blocks.registerBlockType(def.name, {
      edit: Edit,
      save: def.content ? function () { return el(be.InnerBlocks.Content); } : function () { return null; }
    });
  });
})(window.wp, ${JSON.stringify(data).replace(/</g, '\\u003c')});
`;
}

function toTemplate(nodes: any[]): any[] {
  return nodes.filter((n) => n && typeof n.name === 'string').map((n) => [n.name, n.attributes ?? {}, toTemplate(n.innerBlocks ?? [])]);
}

/**
 * The template runtime as plain JS (same rules as customBlocks.ts). Kept as a
 * string so the exported script doesn't depend on how Prepress is bundled.
 * Exported for tests (they run it and compare with fillTemplate).
 */
export const RUNTIME = String.raw`
  var PROTOCOLS = ['http','https','ftp','ftps','mailto','news','irc','irc6','ircs','gopher','nntp','feed','telnet','mms','rtsp','sms','svn','tel','fax','xmpp','webcal','urn'];
  var INLINE = { b:1, strong:1, i:1, em:1, u:1, s:1, a:1, br:1, span:1, code:1, mark:1, sub:1, sup:1, small:1 };
  function escHtml(s) {
    return String(s == null ? '' : s)
      .replace(/&(?!(#[0-9]+|#x[0-9a-fA-F]+|[a-zA-Z][a-zA-Z0-9]*);)/g, '&amp;')
      .replace(/[<>"']/g, function (c) { return { '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#039;' }[c]; });
  }
  function safeUrl(u) {
    var url = String(u == null ? '' : u).trim();
    if (!url) return '';
    if (/^data:image\/(png|jpe?g|gif|webp|avif|svg\+xml)[;,]/i.test(url)) return escHtml(url);
    url = url.replace(/ /g, '%20').replace(/[^a-z0-9\-~+_.?#=!&;,/:%@$|*'()[\]\x80-￿]/gi, '');
    if (!url) return '';
    if (url.indexOf(':') === -1 && ['/', '#', '?'].indexOf(url[0]) === -1 && !/^[a-z0-9-]+?\.php/i.test(url)) url = 'http://' + url;
    var m = url.match(/^([a-z][a-z0-9+.-]*):/i);
    if (m && PROTOCOLS.indexOf(m[1].toLowerCase()) === -1) return '';
    return url.replace(/&(?!#038;)(amp;)?/g, '&#038;').replace(/'/g, '&#039;');
  }
  function safeRichText(h) {
    return String(h == null ? '' : h)
      .replace(/<(script|style|iframe|object|embed|template)[\s\S]*?<\/\1\s*>/gi, '')
      .replace(/<\/?([a-zA-Z][\w-]*)([^>]*)>/g, function (m, tag, rest) {
        var t = tag.toLowerCase();
        if (!INLINE[t]) return '';
        if (m.indexOf('</') === 0) return '</' + t + '>';
        if (t === 'a') {
          var href = rest.match(/\shref\s*=\s*("([^"]*)"|'([^']*)')/i);
          var url = href ? safeUrl((href[2] != null ? href[2] : href[3] || '').replace(/&amp;/g, '&')) : '';
          return url ? '<a href="' + url + '">' : '<a>';
        }
        return t === 'br' ? '<br>' : '<' + t + '>';
      });
  }
  function fmt(a, v) {
    if (v === undefined || v === null) return '';
    var control = a && a.control;
    if (control === 'url' || control === 'image') return safeUrl(v);
    if (control === 'richtext') return safeRichText(v);
    if (a && a.type === 'boolean') return v ? 'true' : '';
    if (a && a.type === 'number') return isFinite(Number(v)) ? String(Number(v)) : '';
    return escHtml(v);
  }
  function truthy(v) { return !(v === undefined || v === null || v === false || v === '' || v === 0); }
  function fill(def, attrs, content) {
    var values = {};
    Object.keys(def.attributes || {}).forEach(function (k) { if (def.attributes[k].default !== undefined) values[k] = def.attributes[k].default; });
    Object.keys(attrs || {}).forEach(function (k) { values[k] = attrs[k]; });
    var out = def.template;
    var section = /\{\{([#^])([a-zA-Z][a-zA-Z0-9]*)\}\}((?:(?!\{\{[#^])[\s\S])*?)\{\{\/\2\}\}/;
    for (var g = 0; g < 200 && section.test(out); g++) {
      out = out.replace(section, function (_m, kind, key, body) { return truthy(values[key]) === (kind === '#') ? body : ''; });
    }
    out = out.replace(/\{\{\{content\}\}\}/g, function () { return content || ''; });
    return out.replace(/\{\{([a-zA-Z][a-zA-Z0-9]*)\}\}/g, function (_m, key) { return fmt(def.attributes[key], values[key]); });
  }
`;

/** functions.php additions: register the site blocks (if any) and the pattern category (if any patterns). */
export function functionsPhpBlocks(defs: CustomBlockDef[], hasPatterns: boolean, fn: string, slug: string): string {
  let out = '';
  if (defs.length) {
    out += `
/**
 * Site blocks made in Prepress (blocks/*). Front end: render.php; editor: assets/prepress-blocks.js.
 */
require_once __DIR__ . '/inc/prepress-blocks.php';

function ${fn}_register_blocks() {
	wp_register_script(
		'prepress-blocks-editor',
		get_theme_file_uri( 'assets/prepress-blocks.js' ),
		array( 'wp-blocks', 'wp-block-editor', 'wp-components', 'wp-element', 'wp-i18n' ),
		wp_get_theme()->get( 'Version' ),
		true
	);
	foreach ( array( ${defs.map((d) => php(blockSlug(d.name))).join(', ')} ) as $block ) {
		register_block_type( __DIR__ . '/blocks/' . $block );
	}
}
add_action( 'init', '${fn}_register_blocks' );
`;
  }
  if (hasPatterns) {
    out += `
/** Pattern category for patterns made in Prepress (patterns/*.php). */
function ${fn}_pattern_category() {
	register_block_pattern_category( ${php(slug)}, array( 'label' => 'Site patterns' ) );
}
add_action( 'init', '${fn}_pattern_category' );
`;
  }
  return out;
}

/** patterns/<slug>.php for an unsynced pattern. */
export function patternPhp(p: { slug: string; title: string; description?: string; content: string; categories?: string[] }, themeSlug: string): string {
  const header = [
    `Title: ${comment(p.title)}`,
    `Slug: ${themeSlug}/${p.slug}`,
    `Categories: ${[themeSlug, ...(p.categories ?? []).map((c) => comment(c).replace(/[^\w -]/g, ''))].join(', ')}`,
    ...(p.description ? [`Description: ${comment(p.description)}`] : []),
  ];
  return `<?php\n/**\n${header.map((l) => ` * ${l}`).join('\n')}\n */\n?>\n${p.content.replace(/<\?/g, '&lt;?')}\n`;
}
